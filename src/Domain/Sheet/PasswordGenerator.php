namespace Proximum\Vimeet\Domain\Sheet;

class PasswordGenerator
{
    public static function generate(int $length = 10): string
    {
        return substr(
            str_shuffle('abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!@#$%^&*()_-=+;:,.?'),
            0,
            $length
        );
    }
}
